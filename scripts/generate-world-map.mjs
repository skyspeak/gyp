// Generates the static geometry and country-name table behind /map:
//
//   npm run map:generate
//
// Commit both outputs. The app never imports d3, topojson or the name
// package at runtime — these are devDependencies — it renders pre-projected
// SVG path strings, so the page ships no mapping library.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { feature } from "topojson-client";
import { geoNaturalEarth1, geoPath, geoCentroid } from "d3-geo";

const require = createRequire(import.meta.url);
const countries = require("i18n-iso-countries");
countries.registerLocale(require("i18n-iso-countries/langs/en.json"));

const topo = JSON.parse(readFileSync(require.resolve("world-atlas/countries-110m.json"), "utf8"));
const fc = feature(topo, topo.objects.countries);

const W = 1000;
const H = 520;
const projection = geoNaturalEarth1().fitExtent([[4, 4], [W - 4, H - 4]], fc);
const path = geoPath(projection);

// Round coordinates: at this size a tenth of a pixel is invisible and it
// roughly halves the payload.
const round = (d) => d.replace(/-?\d+\.\d+/g, (n) => (Math.round(parseFloat(n) * 10) / 10).toString());

// Natural Earth draws French Guiana as part of France. Left alone, every
// program in France also paints the north coast of South America, and the map
// claims there are a dozen gap years in French Guiana. Programs here mean
// metropolitan France, so its overseas polygons are dropped.
const MAINLAND_ONLY = { FR: ([lon]) => lon > -20 };

const out = [];
for (const f of fc.features) {
  if (!f.id) continue; // N. Cyprus, Somaliland, Kosovo: no ISO code to attach programs to
  const code = countries.numericToAlpha2(f.id);
  if (!code) continue;
  const keep = MAINLAND_ONLY[code];
  if (keep && f.geometry.type === "MultiPolygon") {
    f.geometry.coordinates = f.geometry.coordinates.filter((poly) =>
      keep(geoCentroid({ type: "Polygon", coordinates: poly }))
    );
  }
  const d = path(f);
  if (!d) continue;
  const [cx, cy] = projection(geoCentroid(f));
  out.push({
    code,
    name: countries.getName(code, "en", { select: "alias" }) ?? countries.getName(code, "en"),
    d: round(d),
    cx: Math.round(cx),
    cy: Math.round(cy),
  });
}

// Places programs actually go that are too small to exist at 1:110m. They get
// a dot instead of a shape; without this they would silently vanish from the map.
const tiny = { SG: [103.8, 1.35], HK: [114.17, 22.32], SC: [55.45, -4.62], MT: [14.5, 35.9], MU: [57.55, -20.25] };
const dots = Object.entries(tiny).map(([code, lonlat]) => {
  const [cx, cy] = projection(lonlat);
  return { code, name: countries.getName(code, "en", { select: "alias" }), cx: Math.round(cx), cy: Math.round(cy) };
});

writeFileSync(
  "src/lib/world-map.json",
  JSON.stringify({ width: W, height: H, shapes: out.sort((a, b) => a.code.localeCompare(b.code)), dots })
);

// English names for the location parser, pruned of entries that collide with
// something else in this catalog:
//   US  detected in geo.ts with state and token rules instead
//   GE  "Georgia" is almost always the US state
//   JE  would match "New Jersey"
//   VA, UM  never destinations, and their long names only add noise
//   "Congo" names two different countries
//   "UK", "Great Britain"  handled in geo.ts, where "UK-based" can be excluded
//   anything with a comma  formal forms like "Korea, Republic of"
const DROP_CODES = new Set(["US", "GE", "JE", "VA", "UM"]);
const DROP_NAMES = new Set(["Congo", "UK", "Great Britain"]);
const rows = [];
for (const code of Object.keys(countries.getAlpha2Codes()).sort()) {
  if (DROP_CODES.has(code)) continue;
  const keep = (countries.getName(code, "en", { select: "all" }) ?? []).filter(
    (n) => !DROP_NAMES.has(n) && !n.includes(",")
  );
  if (keep.length) rows.push(`  ${code}: ${JSON.stringify(keep)},`);
}
writeFileSync(
  "src/lib/country-names.ts",
  `// Generated by scripts/generate-world-map.mjs — regenerate, don't hand-edit.
// Pruning rules are documented there; dataset-specific aliases live in geo.ts.
export const COUNTRY_NAMES: Record<string, string[]> = {
${rows.join("\n")}
};
`
);

const bytes = readFileSync("src/lib/world-map.json").length;
console.log(`shapes=${out.length} dots=${dots.length} world-map.json=${(bytes / 1024).toFixed(0)}KB`);
